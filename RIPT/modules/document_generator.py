    def get_document_stats(self) -> Dict:
        """Get document generation statistics"""
        if 'generated_documents' not in st.session_state:
            return {
                'total_documents': 0,
                'documents_today': 0,
                'document_types': 0,
                'total_size_kb': 0
            }
        
        documents = st.session_state.generated_documents
        today = datetime.now().date()
        
        return {
            'total_documents': len(documents),
            'documents_today': len([doc for doc in documents 
                                  if doc['generated_date'].date() == today]),
            'document_types': len(set(doc['document_type'] for doc in documents)),
            'total_size_kb': sum(len(doc['content']) for doc in documents) // 1000
        }
