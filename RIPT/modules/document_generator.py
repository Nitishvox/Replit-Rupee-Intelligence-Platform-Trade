    def _show_single_document_generator(self):
        """Single document generation interface"""
        st.subheader("Generate Single Document")
        
        col1, col2 = st.columns([1, 1])
        
        with col1:
            st.markdown("#### Document Configuration")
            
            document_type = st.selectbox("Document Type", self.document_types)
            
            # Dynamic form based on document type
            if document_type == "Trade Settlement Certificate":
                transaction_id = st.text_input("Transaction ID", value="TXN-20250813-001")
                settlement_amount = st.number_input("Settlement Amount (₹)", min_value=0.01, value=100000.0)
                settlement_date = st.date_input("Settlement Date", datetime.now().date())
                from_country = st.selectbox("From Country", ["Russia", "Germany", "UK", "Singapore"])
                to_country = st.selectbox("To Country", ["India"], disabled=True)
                
            elif document_type == "SRVA Account Statement":
                account_id = st.text_input("Account ID", value="SRVA-RUS-001")
                statement_period = st.selectbox("Period", ["Monthly", "Quarterly", "Yearly"])
                start_date = st.date_input("Start Date", datetime.now().date() - timedelta(days=30))
                end_date = st.date_input("End Date", datetime.now().date())
                
            elif document_type == "Compliance Report":
                report_type = st.selectbox("Report Type", ["RBI Compliance", "FEMA Compliance", "AML Report"])
                reporting_period = st.selectbox("Period", ["Monthly", "Quarterly", "Annual"])
                compliance_officer = st.text_input("Compliance Officer", value="Officer Name")
                
            # Document metadata
            st.markdown("#### Document Metadata")
            reference_number = st.text_input("Reference Number", value=f"DOC-{datetime.now().strftime('%Y%m%d%H%M%S')}")
            generated_by = st.text_input("Generated By", value="RIPT System")
            
            # Additional options
            include_watermark = st.checkbox("Include Watermark", value=True)
            include_digital_signature = st.checkbox("Include Digital Signature", value=True)
            
        with col2:
            st.markdown("#### Document Preview")
            
            if st.button("🔍 Generate Preview", type="primary"):
                # Prepare document data
                document_data = {
                    'document_type': document_type,
                    'reference_number': reference_number,
                    'generated_by': generated_by,
                    'generation_date': datetime.now(),
                    'include_watermark': include_watermark,
                    'include_digital_signature': include_digital_signature
                }
                
                # Add specific data based on document type
                if document_type == "Trade Settlement Certificate":
                    document_data.update({
                        'transaction_id': transaction_id,
                        'settlement_amount': settlement_amount,
                        'settlement_date': settlement_date,
                        'from_country': from_country,
                        'to_country': to_country
                    })
                elif document_type == "SRVA Account Statement":
                    document_data.update({
                        'account_id': account_id,
                        'statement_period': statement_period,
                        'start_date': start_date,
                        'end_date': end_date
                    })
                elif document_type == "Compliance Report":
                    document_data.update({
                        'report_type': report_type,
                        'reporting_period': reporting_period,
                        'compliance_officer': compliance_officer
                    })
                
                # Generate document
                document_content = self._generate_document(document_data)
                
                if document_content:
                    st.success("✅ Document generated successfully!")
                    
                    # Display document preview
                    st.markdown("##### 📄 Document Content")
                    st.markdown(document_content, unsafe_allow_html=True)
                    
                    # Download button
                    st.download_button(
                        label="📥 Download Document",
                        data=document_content,
                        file_name=f"{reference_number}_{document_type.replace(' ', '_')}.html",
                        mime="text/html"
                    )
                    
                    # Save to session for library
                    if 'generated_documents' not in st.session_state:
                        st.session_state.generated_documents = []
                    
                    st.session_state.generated_documents.append({
                        'reference_number': reference_number,
                        'document_type': document_type,
                        'generated_date': datetime.now(),
                        'content': document_content,
                        'metadata': document_data
                    })
                
