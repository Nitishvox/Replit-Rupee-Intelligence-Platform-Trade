    def _show_document_library(self):
        """Document library interface"""
        st.subheader("Document Library")
        
        if 'generated_documents' in st.session_state and st.session_state.generated_documents:
            documents = st.session_state.generated_documents
            
            # Summary metrics
            col1, col2, col3, col4 = st.columns(4)
            
            with col1:
                st.metric("Total Documents", len(documents))
            
            with col2:
                doc_types = [doc['document_type'] for doc in documents]
                unique_types = len(set(doc_types))
                st.metric("Document Types", unique_types)
            
            with col3:
                today_docs = len([doc for doc in documents 
                                if doc['generated_date'].date() == datetime.now().date()])
                st.metric("Generated Today", today_docs)
            
            with col4:
                # Calculate total size (mock)
                total_size = len(documents) * 50  # KB
                st.metric("Total Size", f"{total_size} KB")
            
            # Document list
            st.markdown("#### Document List")
            
            document_df = pd.DataFrame([
                {
                    'Reference': doc['reference_number'],
                    'Type': doc['document_type'],
                    'Generated': doc['generated_date'].strftime('%Y-%m-%d %H:%M'),
                    'Size': f"{len(doc['content'])//1000} KB"
                }
                for doc in documents
            ])
            
            st.dataframe(document_df, use_container_width=True)
            
            # Document viewer
            st.markdown("#### Document Viewer")
            
            selected_ref = st.selectbox("Select Document to View", 
                                      [doc['reference_number'] for doc in documents])
            
            if selected_ref:
                selected_doc = next((doc for doc in documents 
                                   if doc['reference_number'] == selected_ref), None)
                
                if selected_doc:
                    col1, col2 = st.columns([3, 1])
                    
                    with col1:
                        st.markdown("##### Document Content")
                        st.markdown(selected_doc['content'], unsafe_allow_html=True)
                    
