    def _generate_document(self, document_data: Dict) -> str:
        """Generate document based on type and data"""
        document_type = document_data['document_type']
        
        if document_type in self.templates:
            return self.templates[document_type](document_data)
        else:
            return self._generate_generic_document(document_data)
    
